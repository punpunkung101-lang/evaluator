#!/usr/bin/env node
"use strict";

const fs = require("node:fs");
const path = require("node:path");
const crypto = require("node:crypto");

const databaseDir = path.resolve(__dirname, "..");
const bank = JSON.parse(fs.readFileSync(path.join(databaseDir, "question-bank.json"), "utf8"));
const outputPath = path.join(databaseDir, "questions_seed.sql");
const sqlText = (value) => `'${String(value ?? "").replaceAll("'", "''")}'`;
const sqlJson = (value) => sqlText(JSON.stringify(value ?? null));
const bool = (value) => value ? 1 : 0;

function generateQuestionsSeed(questionBank = bank) {
  const lines = [
    "-- Generated from database/question-bank.json by database/build/generate-questions-seed.cjs.",
    "-- Do not edit this file by hand.",
    "PRAGMA foreign_keys = ON;",
    "BEGIN IMMEDIATE;",
  ];

  for (const question of questionBank.questions) {
    const metadata = { ...question };
    for (const key of ["id", "system_id", "assessment_type", "section", "text", "text_en", "answer_type", "options", "required", "is_scored", "indicator_group", "step", "order", "roles", "visible_when", "allow_na", "allow_other", "max_select"]) delete metadata[key];
    lines.push(
      `INSERT OR IGNORE INTO assessment_questions(id,system_id,assessment_type,section,text,text_en,answer_type,options_json,required,is_scored,indicator_group,step,question_order,roles_json,visible_when_json,allow_na,allow_other,max_select,option_set_ref,metadata_json) VALUES(${[
        sqlText(question.id), question.system_id == null ? "NULL" : sqlText(question.system_id), sqlText(question.assessment_type), sqlText(question.section), sqlText(question.text), sqlText(question.text_en), sqlText(question.answer_type), sqlJson(question.options), bool(question.required), bool(question.is_scored), sqlText(question.indicator_group), question.step, question.order, sqlJson(question.roles), sqlJson(question.visible_when), bool(question.allow_na), bool(question.allow_other), question.max_select == null ? "NULL" : question.max_select, question.option_set_ref ? sqlText(question.option_set_ref) : "NULL", sqlJson(metadata),
      ].join(",")});`
    );
  }

  for (const set of questionBank.option_sets) {
    lines.push(`INSERT OR IGNORE INTO option_sets(id,system_id,options_json,values_by_system_json,values_by_role_json,depends_on_json,metadata_json) VALUES(${[
      sqlText(set.id), set.system_id == null ? "NULL" : sqlText(set.system_id), sqlJson(set.options || []), sqlJson(set.values_by_system || {}), sqlJson(set.values_by_role || {}), sqlJson(set.depends_on || {}), sqlJson(Object.fromEntries(Object.entries(set).filter(([key]) => !["id", "system_id", "options", "values_by_system", "values_by_role", "depends_on"].includes(key)))),
    ].join(",")});`);
  }

  for (const system of questionBank.systems) {
    for (const assessmentType of ["effectiveness", "satisfaction"]) {
      const formId = `${system.id}-${assessmentType}`;
      const versionId = `${formId}-v1`;
      const title = `${system.name} — ${assessmentType === "effectiveness" ? "ประสิทธิผล" : "ความพึงพอใจ"}`;
      const formQuestions = questionBank.questions.filter((question) => question.assessment_type === assessmentType && (question.system_id == null || question.system_id === system.id));
      const relevantRules = questionBank.answer_rules.filter((rule) => (rule.question_ids || []).every((id) => formQuestions.some((question) => question.id === id)));
      const optionSetIds = new Set(formQuestions.map((question) => question.option_set_ref).filter(Boolean));
      const relevantOptionSets = questionBank.option_sets.filter((set) => optionSetIds.has(set.id));
      const definition = JSON.stringify({ formId, assessmentType, questions: formQuestions, optionSets: relevantOptionSets, rules: relevantRules });
      const contentHash = crypto.createHash("sha256").update(definition).digest("hex");
      lines.push(`INSERT OR IGNORE INTO assessment_forms(id,system_id,assessment_type,title,active,current_version_id) VALUES(${[sqlText(formId), sqlText(system.id), sqlText(assessmentType), sqlText(title), "1", "NULL"].join(",")});`);
      lines.push(`INSERT OR IGNORE INTO form_versions(id,form_id,version_number,status,content_hash,created_at) VALUES(${[sqlText(versionId), sqlText(formId), "1", sqlText("published"), sqlText(contentHash), sqlText("2026-11-12T00:00:00Z")].join(",")});`);
      formQuestions.forEach((question, index) => {
        lines.push(`INSERT OR IGNORE INTO form_version_questions(form_version_id,question_id,step,sort_order) VALUES(${[sqlText(versionId), sqlText(question.id), question.step, index + 1].join(",")});`);
      });
      for (const rule of relevantRules) {
        lines.push(`INSERT OR IGNORE INTO answer_rules(id,form_version_id,rule_type,question_ids_json,rule_json) VALUES(${[sqlText(rule.id), sqlText(versionId), sqlText(rule.type), sqlJson(rule.question_ids), sqlJson(rule)].join(",")});`);
      }
      lines.push(`UPDATE assessment_forms SET current_version_id=${sqlText(versionId)} WHERE id=${sqlText(formId)};`);
    }
  }
  lines.push("COMMIT;", "");
  return lines.join("\n");
}

if (require.main === module) {
  fs.writeFileSync(outputPath, generateQuestionsSeed(), "utf8");
  process.stdout.write(`Generated ${outputPath} from ${bank.questions.length} questions.\n`);
}

module.exports = { generateQuestionsSeed };
